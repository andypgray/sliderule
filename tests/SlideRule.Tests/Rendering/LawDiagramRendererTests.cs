                s_Domain --x s_Web
                s_Web --x|"expose"| s_Vendor_Engine
                s_Shop_Pack -->|"only"| s_Domain
                s_Shop_Web_Controllers -.-x|"grandfathered"| s_System_Data_DataTable

                subgraph l_legend["Legend"]
                    l_ban["--x = must not reference"]
                    l_expose["--x expose = must not expose on a public signature"]
                    l_only["--> only = the only references allowed"]
                    l_debt["-.-x grandfathered = Migrate debt, with the existing sites baselined"]
                    l_quarantine["Quarantine box = a contained scope; the doubled boxes are its sanctioned surface"]
                    l_outside["Rounded box = a place named only as the target of a rule"]
                    l_nesting["A box inside a box = the inner place is part of the outer"]
                end
            ```

            Not drawn in full: `naming/interfaces`, `legacy/pricing/tripwire` (Quarantine). Expand any of them with `sliderule explain <rule-id>`.
            """);
    }

    [Fact]
    public void Block_TheTwoBanVerbs_PointInOppositeDirections()
    {
        // Arrange — the same two places, said from each end.
        ArchitectureModel model = Checker.Model(arch =>
        {
            arch.Rule("r/out")
                .Enforce(arch.Namespace("A.*").MustNotReference(arch.Namespace("B.*")))
                .Because("x");
            arch.Rule("r/in")
                .Enforce(arch.Namespace("C.*").MustNotBeReferencedBy(arch.Namespace("D.*")))
                .Because("x");
        });

        // Act
        string block = LawDiagramRenderer.Block(model, SpecName);

        // Assert — MustNotBeReferencedBy is the inbound voice: the operand is the source of the arrow.
        Edges(block)
            .ShouldBe(["s_A --x s_B", "s_D --x s_C"]);
    }

