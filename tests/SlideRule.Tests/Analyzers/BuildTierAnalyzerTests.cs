    // Each warning as one sorted line carrying everything a reader of a build log sees — the ID, the whole
    // span, the properties and the message — because two runs that agreed on the count and differed on any
    // of the four would otherwise compare equal.
    private static List<string> Lines(IEnumerable<Diagnostic> reported)
    {
        return reported.Select(Line)
            .OrderBy(line => line, StringComparer.Ordinal)
            .ToList();
    }

    private static string Line(Diagnostic diagnostic)
    {
        FileLinePositionSpan span = diagnostic.Location.GetLineSpan();
        string place = string.IsNullOrEmpty(span.Path)
            ? "(no location)"
            : $"{span.Path}({span.StartLinePosition},{span.EndLinePosition})";
        IEnumerable<string> properties = diagnostic.Properties
            .OrderBy(property => property.Key, StringComparer.Ordinal)
            .Select(property => $"{property.Key}={property.Value}");

        return $"{diagnostic.Id} {place} [{string.Join(", ", properties)}] "
               + diagnostic.GetMessage(CultureInfo.InvariantCulture);
    }

    private static string WithSchemaVersion(string text, string version)
    {
        return text.Replace("\"schemaVersion\": 2,", $"\"schemaVersion\": {version},");
    }
