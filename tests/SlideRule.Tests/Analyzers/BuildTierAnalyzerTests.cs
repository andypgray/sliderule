    [Fact]
    public async Task TheLiveTier_UnderParallelAndSequentialAnalysis_ReportsTheSameSet()
    {
        // The batch run analyses the documents concurrently, the per-document run one at a time. The state
        // the two share is built once at compilation start, so the two must agree — and a race that loses
        // once in a while would not show in a single pass.
        for (var pass = 1; pass <= 5; pass++)
        {
            IReadOnlyList<Diagnostic> concurrent = await EnforcedAsync(EightDocuments());
            IReadOnlyDictionary<string, IReadOnlyList<Diagnostic>> sequential =
                await EnforcedPerDocumentAsync(EightDocuments());

            List<Diagnostic> oneAtATime = sequential.Values
                .SelectMany(document => document)
                .ToList();
            Lines(concurrent)
                .ShouldBe(Lines(oneAtATime), $"pass {pass}: the concurrent run and the sequential one disagree");
