    // The rules a pair of rows shares, so the two arms of each differ only in the source they read.
    private static void ConstructRule(Arch arch)
    {
        arch.Rule("span/does-not-construct")
            .Enforce(arch.Types.Named("Builder").MustNotConstruct(arch.Types.Named("Store")))
            .Because(SpanBecause);
    }

    private static void CatchRule(Arch arch)
    {
        arch.Rule("span/does-not-catch")
            .Enforce(arch.Types.Named("Catcher").MustNotCatch(arch.Types.Named("Fault")))
            .Because(SpanBecause);
    }

    private static void ThrowRule(Arch arch)
    {
        arch.Rule("span/does-not-throw")
            .Enforce(arch.Types.Named("Thrower").MustNotThrow(arch.Types.Named("Fault")))
            .Because(SpanBecause);
    }

    // One document breaking one rule at one site, and the warning it earns — the shape every per-channel
