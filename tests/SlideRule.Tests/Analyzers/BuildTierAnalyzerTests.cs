/// <summary>
///     The build-tier analyzer over one project's compilation: which warnings it reports, where it puts
///     them, and the far larger set of cases in which it says nothing at all.
/// </summary>
/// <remarks>
///     <para>
///         Silence is the subject of most of these facts, and on purpose: the analyzer may report only
///         what a check over the whole solution would report, so every case it cannot settle from one
///         compilation has to end quiet rather than in a guess. Each such fact names the case it is about.
///     </para>
///     <para>
///         The rows about a broken rule run on both forms a reference to another project can take — the
///         other compilation's source symbols, and a metadata image of it — because a build hands over the
///         second and an editor the first, and a warning must not depend on which.
///     </para>
///     <para>
///         The live tier answers per document and the build tier once per compilation, so the rows that
///         name a tier come in pairs: what the whole compilation reports, which is the same set on either
///         tier, and what one document reports when it is asked on its own, which is where the live tier's
///         findings actually come from.
///     </para>
/// </remarks>
public sealed class BuildTierAnalyzerTests
{
