using Microsoft.CodeAnalysis.Emit;
using Microsoft.CodeAnalysis.Text;
using Shouldly;
using SlideRule.Cli.SpecLoading;
using SlideRule.Tests.TestSupport;
using Xunit;

namespace SlideRule.Tests.Cli;

/// <summary>
///     The spec-source comparison over hand-built project directories, each compiled to a DLL with a portable PDB
///     beside it, embedded in it, or none, so the checksum arm reads the document hashes a real build records.
/// </summary>
/// <remarks>
///     Every build's write time is set an hour back after emitting, and every file meant to predate the build two
///     hours back, so a verdict that rests on write times is never decided by file-system timestamp granularity.
/// </remarks>
public sealed class SpecSourceComparisonTests
{
    private const string ProjectName = "MyApp.Architecture";
    private const string RulesSource = "public sealed class Rules { }";
    private const string EditedRulesSource = "public sealed class Rules { public int Added; }";

    [Fact]
    public void Compare_SourcesMatchTheBuild_ReportsNothing()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);

        bed.Compare()
            .ShouldBeNull();
    }

    [Fact]
    public void Compare_EditedSource_ReportsItChangedByChecksum()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        File.WriteAllText(bed.Rules, EditedRulesSource);

        bed.Compare()
            .ShouldBe(bed.Stale(bed.Rules, StaleReason.Changed, SpecComparison.Checksum));
    }

    [Fact]
    public void Compare_EditRevertedToTheBuiltBytes_ReportsNothing()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        File.WriteAllText(bed.Rules, EditedRulesSource);
        File.WriteAllText(bed.Rules, RulesSource);

        bed.Compare()
            .ShouldBeNull();
    }

    [Fact]
    public void Compare_TouchedSourceWithItsBytesUnchanged_ReportsNothing()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        File.SetLastWriteTimeUtc(bed.Rules, DateTime.UtcNow);

        bed.Compare()
            .ShouldBeNull();
    }

    [Fact]
    public void Compare_DeletedSource_ReportsItMissing()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        File.Delete(bed.Rules);

        bed.Compare()
            .ShouldBe(bed.Stale(bed.Rules, StaleReason.Missing, SpecComparison.Checksum));
    }

    [Fact]
    public void Compare_SourceAddedAfterTheBuild_ReportsItAdded()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        string added = bed.Temp.WriteFile(["MyApp.Architecture", "Layers", "Added.cs"], "public sealed class Added { }");

        bed.Compare()
            .ShouldBe(bed.Stale(added, StaleReason.Added, SpecComparison.Checksum));
    }

    [Fact]
    public void Compare_UncompiledSourceOlderThanTheBuild_ReportsNothing()
    {
        // The shape a Compile Remove leaves: a file below the project directory that the build never compiled.
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        string excluded = bed.Temp.WriteFile(["MyApp.Architecture", "Excluded.cs"], "public sealed class Excluded { }");
        bed.Backdate(excluded);

        bed.Compare()
            .ShouldBeNull();
    }

    [Fact]
    public void Compare_GeneratedDocumentUnderObjEdited_ReportsNothing()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        File.WriteAllText(bed.Generated, "// regenerated by every build");

        bed.Compare()
            .ShouldBeNull();
    }

    [Fact]
    public void Compare_SourceInANestedProjectsDirectory_ReportsNothing()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        bed.Temp.WriteFile(["MyApp.Architecture", "Nested", "Nested.csproj"], "<Project />");
        bed.Temp.WriteFile(["MyApp.Architecture", "Nested", "Other.cs"], "public sealed class Other { }");

        bed.Compare()
            .ShouldBeNull();
    }

    [Fact]
    public void Compare_SpecProjectUnderAFolderNamedObj_EditReportsItChangedByChecksum()
    {
        // Only a segment below the project directory makes a document generated, never one above it.
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb, under: "obj");
        File.WriteAllText(bed.Rules, EditedRulesSource);

        bed.Compare()
            .ShouldBe(bed.Stale(bed.Rules, StaleReason.Changed, SpecComparison.Checksum));
    }

    [Fact]
    public void Compare_SourceAddedBesideAnInaccessibleDirectory_StillReportsItAdded()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        string added = bed.AddBesideADeniedDirectory();

        bed.Compare()
            .ShouldBe(bed.Stale(added, StaleReason.Added, SpecComparison.Checksum));
    }

    [Fact]
    public void Compare_NoPdbAndASourceAddedBesideAnInaccessibleDirectory_StillReportsItNewer()
    {
        using var bed = SpecBed.Build(debugFormat: null);
        string added = bed.AddBesideADeniedDirectory();

        bed.Compare()
            .ShouldBe(bed.Stale(added, StaleReason.Newer, SpecComparison.FileTime));
    }

    [Fact]
    public void Compare_EditedSourceWhosePdbRecordsSha1_ReportsItChangedByChecksum()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb, checksumAlgorithm: SourceHashAlgorithm.Sha1);
        File.WriteAllText(bed.Rules, EditedRulesSource);

        bed.Compare()
            .ShouldBe(bed.Stale(bed.Rules, StaleReason.Changed, SpecComparison.Checksum));
    }

    [Fact]
    public void Compare_EditedSourceWithAnEmbeddedPdb_ReportsItChangedByChecksum()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.Embedded);
        File.WriteAllText(bed.Rules, EditedRulesSource);

        bed.Compare()
            .ShouldBe(bed.Stale(bed.Rules, StaleReason.Changed, SpecComparison.Checksum));
    }

    [Fact]
    public void Compare_NoPdbAndATouchedSource_ReportsItNewerByFileTime()
    {
        using var bed = SpecBed.Build(debugFormat: null);
        File.SetLastWriteTimeUtc(bed.Rules, DateTime.UtcNow);

        bed.Compare()
            .ShouldBe(bed.Stale(bed.Rules, StaleReason.Newer, SpecComparison.FileTime));
    }

    [Fact]
    public void Compare_NoPdbAndSourcesOlderThanTheBuild_ReportsNothing()
    {
        using var bed = SpecBed.Build(debugFormat: null);

        bed.Compare()
            .ShouldBeNull();
    }

    [Fact]
    public void Compare_PdbWhoseDocumentPathsWereMapped_FallsBackToFileTimes()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb, mapPaths: true);
        File.SetLastWriteTimeUtc(bed.Rules, DateTime.UtcNow);

        bed.Compare()
            .ShouldBe(bed.Stale(bed.Rules, StaleReason.Newer, SpecComparison.FileTime));
    }

    [Fact]
    public void Compare_ResolutionOfASpecPassedAsADll_ReportsNothing()
    {
        // A built DLL names no project, so there are no sources to compare, even with an edited one beside it.
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        File.WriteAllText(bed.Rules, EditedRulesSource);

        SpecSourceComparison.Compare(new SpecResolution(bed.Dll, null, []))
            .ShouldBeNull();
    }

    [Fact]
    public void Compare_ResolutionOfASpecProject_ComparesItsSources()
    {
        using var bed = SpecBed.Build(DebugInformationFormat.PortablePdb);
        File.WriteAllText(bed.Rules, EditedRulesSource);

        SpecSourceComparison.Compare(new SpecResolution(bed.Dll, ProjectName, [ProjectName], ProjectFilePath: bed.Project))
            .ShouldBe(bed.Stale(bed.Rules, StaleReason.Changed, SpecComparison.Checksum));
    }

    // A spec project directory with two sources and one generated document under obj, built to bin, in the temp
    // directory or in a folder of it named by under.
    private sealed class SpecBed : IDisposable
    {
        private readonly string[] _project;
        private ScopedDirectoryDenial? _denial;

        private SpecBed(TempDirectory temp, string? under)
        {
            string[] project = under is null ? ["MyApp.Architecture"] : [under, "MyApp.Architecture"];
            _project = project;
            Temp = temp;
            Project = temp.WriteFile([.. project, "MyApp.Architecture.csproj"], "<Project />");
            Rules = temp.WriteFile([.. project, "Rules.cs"], RulesSource);
            Layer = temp.WriteFile([.. project, "Layers", "Layer.cs"], "public sealed class Layer { }");
            Generated = temp.WriteFile([.. project, "obj", "Debug", "Generated.cs"], "public sealed class Generated { }");
            Dll = temp.PathOf([.. project, "bin", "Debug", "MyApp.Architecture.dll"]);
        }

        public TempDirectory Temp { get; }

        public string Project { get; }

        public string Rules { get; }

        public string Generated { get; }

        public string Dll { get; }

        private string Layer { get; }

        public void Dispose()
        {
            try
            {
                _denial?.Dispose();
            }
            finally
            {
                Temp.Dispose();
            }
        }

        public static SpecBed Build(
            DebugInformationFormat? debugFormat, bool mapPaths = false,
            SourceHashAlgorithm checksumAlgorithm = SourceHashAlgorithm.Sha256, string? under = null)
        {
            var bed = new SpecBed(TestTempRoot.Fresh("spec-source-comparison"), under);
            try
            {
                Directory.CreateDirectory(Path.GetDirectoryName(bed.Dll)!);
                string projectDirectory = Path.GetDirectoryName(bed.Project)!;
                // A mapped document takes the "/_/" root a CI build's path map gives it, so it resolves nowhere here.
                Func<string, string>? recordedPath = mapPaths
                    ? path => "/_/" + Path.GetRelativePath(projectDirectory, path).Replace('\\', '/')
                    : null;
                SpecAssemblyCompiler.EmitFromFiles(
                    [bed.Rules, bed.Layer, bed.Generated], bed.Dll, debugFormat, recordedPath, checksumAlgorithm);

                foreach (string source in new[] { bed.Project, bed.Rules, bed.Layer, bed.Generated }) bed.Backdate(source);
                DateTime builtAt = DateTime.UtcNow.AddHours(-1);
                File.SetLastWriteTimeUtc(bed.Dll, builtAt);
                if (debugFormat == DebugInformationFormat.PortablePdb)
                    File.SetLastWriteTimeUtc(Path.ChangeExtension(bed.Dll, ".pdb"), builtAt);

                return bed;
            }
            catch
            {
                bed.Dispose();
                throw;
            }
        }

        // A source added after the build beside a directory holding another that the walk cannot list. The bed lifts
        // the denial before it deletes its directory.
        public string AddBesideADeniedDirectory()
        {
            Temp.WriteFile([.. _project, "Denied", "Unseen.cs"], "public sealed class Unseen { }");
            string added = Temp.WriteFile([.. _project, "Added.cs"], "public sealed class Added { }");
            _denial = ScopedDirectoryDenial.Deny(Temp.PathOf([.. _project, "Denied"]));
            return added;
        }

        public void Backdate(string path)
        {
            File.SetLastWriteTimeUtc(path, DateTime.UtcNow.AddHours(-2));
        }

        public StaleSpec? Compare()
        {
            return SpecSourceComparison.Compare(Dll, ProjectName, Project);
        }

        public StaleSpec Stale(string file, StaleReason reason, SpecComparison comparison)
        {
            return new StaleSpec(ProjectName, Project, file, reason, comparison);
        }
    }
}
