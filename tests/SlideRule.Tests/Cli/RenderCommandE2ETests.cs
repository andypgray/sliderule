    public async Task Render_Fresh_WritesPinnedRootAndScopeFilesAndNoLayerCards()
    {
        // Web's card is asserted absent because its absence is half the claim: MyAppRenderSpec
        // declares Domain and Web layers but anchors no rule on either, so every file render does emit here
        // is a *scope* card — the billing quarantine's and the domain caution's — and never a layer card. Web
