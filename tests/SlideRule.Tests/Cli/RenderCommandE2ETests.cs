/// <summary>
///     End-to-end <c>render</c> against this class's own copy of the MyApp fixture solution: the files each
///     target writes (the managed blocks, the <c>--diagram</c> target, the model file) and the lines it
///     reports, idempotence, hand content around the markers, the persisted extraction cache, the Claude Code
///     instruction-file warnings, a committed <c>sliderule.json</c> that gives <c>check</c> and <c>render</c>
///     the spec and the render targets no argument names, and <c>render --check</c> comparing every target with
///     what is on disk while writing nothing.
/// </summary>
/// <remarks>
///     A render test in particular must own its copy. The render targets are this class's
///     subject, so every row here writes them. Written in place they land in the bin-copied fixture bed
///     that <see cref="TempFixtureWorkspace" /> copies <em>from</em>, and nothing removes them: a build
///     never deletes a file a test wrote into its output, so the last row's cards outlive the run and
///     arrive in every other class's copy of MyApp as files the fixture does not ship. Downstream that is
///     indistinguishable from a fixture file, and a row that renders a different spec over it reads
///     <c>unchanged</c> where it expects <c>wrote</c> — decided by whichever spec wrote the bed last.
///     The copy's reset closes that off, so no row needs a teardown of its own.
/// </remarks>
